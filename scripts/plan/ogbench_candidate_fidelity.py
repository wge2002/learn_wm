"""Audit CEM decision fidelity on OGBench Cube with true MuJoCo rollouts.

The ordinary world-model loss asks whether a fixed action sequence has a
small prediction error.  This audit asks the control-facing question instead:
given the *same* CEM population, does the learned cost rank and refit the
candidates in the same way as the simulator oracle?

For every paired dataset state and selected CEM round, the script:

1. records complete populations generated by each requested checkpoint;
2. scores every population with every requested checkpoint;
3. replays every candidate from the exact qpos/qvel start state in MuJoCo;
4. compares predicted and true top-k sets and their CEM update directions.

The first population is generated with common random numbers, so it is exactly
paired across generators.  Later populations expose path-dependent optimizer
feedback.  ``audit.max_candidates=-1`` is required for formal proposal and
top-k coverage claims; positive values are intended only for smoke tests.

Example:

  python scripts/plan/ogbench_candidate_fidelity.py \
      policy=/path/to/k1.pt \
      plan_config.horizon=10 plan_config.receding_horizon=10 \
      +plan_config.history_len=3 eval.goal_offset_steps=50 \
      +audit.generators=/path/to/k1.pt,/path/to/k5.pt \
      +audit.scorers=/path/to/k1.pt,/path/to/k5.pt \
      +audit.labels=K1,K5 +audit.num_states=8 \
      +audit.steps=0,4,9,19,29 +audit.max_candidates=-1 \
      +audit.sim_workers=4 \
      +audit.include_expert_anchors=true \
      +audit.init_prior=zero \
      '+audit.expert_noise_scales="0.02,0.05,0.1"' \
      +audit.min_initial_distance=0.04 \
      +audit.out=/tmp/ogbench_candidate_fidelity.npz
"""

